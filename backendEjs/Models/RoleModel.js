import mongoose from "mongoose";

const roleSchema = new mongoose.Schema({
    roleName: {
        type: String
    },
    roleDescription: {
        type: String
    },
    branchID: {
        type: Number
    },
    createdBy : {
        type: String
    },
    updatedBy : {
        type : String
    },
    deletedBy: {
        type: String
    },
    deletedAt: {
        type: String
    },
    isActive: {
        type: Boolean,
        default: true
    },
    isDeleted: {
        type: Boolean,
        default: false
    }
},{
    timestamps: true
})

const Role = mongoose.model("Role", roleSchema)

export default Role